fn glyph(c: char) -> [u8; 7] {
    let upper = c.to_ascii_uppercase();
    GLYPHS
        .iter()
        .find(|(candidate, _)| *candidate == upper)
        .map(|(_, rows)| *rows)
        .unwrap_or([0; 7])
}

/// Width of `characters` glyphs at `scale`, excluding trailing glyph spacing.
pub fn text_width(characters: usize, scale: u32) -> u32 {
    if characters == 0 {
        return 0;
    }
    (characters as u32 * ADVANCE - 1) * scale
}

/// Draw ASCII text from `(x, y)`, normalizing case and leaving unmapped glyphs blank.
pub fn draw(
    canvas: &mut crate::raster::Canvas,
    x: i64,
    y: i64,
    text: &str,
    scale: u32,
    color: [u8; 3],
) {
    let pixel = [color[0], color[1], color[2], 255];
    let mut cursor = x;
    for character in text.chars() {
        for (row, bits) in glyph(character).iter().enumerate() {
            for column in 0..5u32 {
                if bits & (1 << (4 - column)) == 0 {
                    continue;
                }
                canvas.fill_rect(
                    cursor + i64::from(column * scale),
                    y + (row as u32 * scale) as i64,
                    scale,
                    scale,
                    pixel,
                );
            }
        }
        cursor += i64::from(ADVANCE * scale);
    }
}
